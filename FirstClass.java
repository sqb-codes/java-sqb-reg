public class FirstClass {
    // int x = 12;
    public static void main(String[] args) {
        System.out.println("Hello World...");
        /*
        System.out.print - print in same line
        System.out.println - print in a new line
        System - pre-defined class
        out - object belongs to PrintStream class
        out is a member of system class
        println - method inside PrintStream class
         */
    }
}

// public - global, which is accessible for all, from anywhere

/*
4 types of scope:
1. Public - accessible from anywhere
2. Private - accessible only within class
3. Protected - can be accessed inside the package, can also be accessed outside the package using inheritance
4. Default - it you will not specify the scope then it is default, it can be accessed by any class but within same package (folder)
 */

